/** 남중이 시계 정오보다 얼마나 늦는지 말로 */
export function noonWord(late) {
  if (late < 28) return '표준시 자오선에 가까운 편이라 남중이 비교적 이릅니다';
  if (late < 31) return '시계의 정오와 해의 정오가 반 시간쯤 어긋납니다';
  if (late < 33) return '해가 꼭대기에 오르기까지 정오를 한참 넘깁니다';
  return '우리 커버리지에서 남중이 가장 늦는 축에 듭니다';
}
/** 하짓날 낮 길이를 말로 */
export function dayWord(min) {
  if (min >= 886) return '여름 낮이 유난히 길게 늘어지는 위도입니다';
  if (min >= 880) return '여름 낮이 긴 편입니다';
  if (min >= 874) return '여름 낮 길이가 한가운데쯤입니다';
  return '우리 커버리지에서는 여름 낮이 짧은 쪽입니다';
}
/** 해가 진 뒤 방문에 관한 한마디 */
export function duskWord(setHHMM) {
  const m = Number(setHHMM.slice(0, 2)) * 60 + Number(setHHMM.slice(3, 5));
  if (m >= 1196) return '여름 저녁 여덟 시 가까이까지 밖이 환합니다';
  if (m >= 1190) return '여름에는 일곱 시 반을 넘겨도 아직 밝습니다';
  if (m >= 1182) return '여름 저녁이 꽤 오래 밝은 자리입니다';
  return '여름이어도 해가 비교적 일찍 넘어갑니다';
}
/** 위도 차례를 말로 */
export function northWord(rank, total) {
  const p = rank / total;
  if (p <= 0.08) return '쪽을 낸 칸 가운데 가장 북쪽 무리에 듭니다';
  if (p <= 0.33) return '북쪽에 치우친 자리입니다';
  if (p <= 0.67) return '남북으로 보면 한가운데쯤입니다';
  if (p <= 0.92) return '남쪽에 치우친 자리입니다';
  return '쪽을 낸 칸 가운데 가장 남쪽 무리에 듭니다';
}
/** 넓이를 걸음으로 — 땅을 재는 축이 아니라 '해가 비치는 범위'로 쓴다 */
export function spanWord(a) {
  if (a < 1) return '한 칸 안에서는 해 그림자 길이가 거의 같습니다';
  if (a < 3) return '칸이 좁아 어느 집에서 보든 해가 같은 자리에 있습니다';
  if (a < 10) return '칸이 제법 넓어 끝과 끝의 해넘이가 몇 초쯤 벌어집니다';
  if (a < 30) return '칸이 넓어 안쪽에서도 차로 움직이게 됩니다';
  return '한 이름 안에서 끝에서 끝까지 가는 데만 한참 걸립니다';
}

